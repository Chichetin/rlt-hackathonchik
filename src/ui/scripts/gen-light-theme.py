"""Generate src/light-theme.generated.css: the dark stylesheets' hard-coded colours mapped to the light palette (#619).
Run from src/ui: python scripts/gen-light-theme.py. Only declarations that contain a colour are re-emitted,
each rule prefixed with html[data-theme="light"]; src/light-theme.css holds the hand-made corrections."""
import colorsys, re, sys
from pathlib import Path

ORDER = ["styles", "glass", "search-compose", "responsive-ui", "results-view", "interior-ui", "supplier-results",
         "work-glass", "work-typography", "results-reader", "micro", "examples", "filters", "testset", "ratings",
         "external-reviews", "search-loading", "backtest"]
FLAGS = set()
NAVY = (0x14, 0x23, 0x3F)
COLOR = re.compile(r"#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3,4}\b|rgba?\([^)]*\)")

def parse(tok):
    if tok.startswith("#"):
        h = tok[1:]
        if len(h) in (3, 4): h = "".join(c * 2 for c in h)
        r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
        return r, g, b, a
    nums = [float(x) for x in re.findall(r"[\d.]+", tok)[:4]]
    if "/" in tok or len(nums) < 3: return None
    return nums[0], nums[1], nums[2], (nums[3] if len(nums) > 3 else 1.0)

def lum(r, g, b): return colorsys.rgb_to_hls(r / 255, g / 255, b / 255)[1]

def hexa(r, g, b, a=1.0):
    s = "#%02x%02x%02x" % (round(r), round(g), round(b))
    return s if a >= 0.995 else s + "%02x" % round(a * 255)

def hue(r, g, b): return colorsys.rgb_to_hls(r / 255, g / 255, b / 255)[0] * 360

def sat(r, g, b): return colorsys.rgb_to_hls(r / 255, g / 255, b / 255)[2]

def map_text(r, g, b, a):
    l = lum(r, g, b)
    if l < 0.4: return None  # already dark enough
    if sat(r, g, b) > 0.25 and l > 0.45:
        h = hue(r, g, b)
        if 90 < h < 180: return (0x0b, 0x5a, 0x44, a)   # green
        if 20 < h < 70: return (0x7a, 0x4d, 0x00, a)    # amber
        if h < 20 or h > 330: return (0x9b, 0x1c, 0x1c, a)  # red
        return (0x1b, 0x4b, 0x91, a)                    # blue / violet
    return (0x14, 0x23, 0x3F, a) if l > 0.8 else (0x46, 0x55, 0x6E, a)

def map_line(r, g, b, a):
    if lum(r, g, b) > 0.6 and a < 1: return (*NAVY, min(1.0, a + 0.1))
    if lum(r, g, b) > 0.6: return (0x9a, 0xa6, 0xb8, 1.0)
    return None

def map_bg(r, g, b, a):
    l = lum(r, g, b)
    if a < 0.995:
        if l > 0.6: return (*NAVY, a * 0.8)       # white tint -> navy tint
        if l < 0.35 and a > 0.4: return (255, 255, 255, a)  # dense black veil -> white veil
        return None
    if l < 0.3: return (255, 255, 255, 1.0)       # dark surface -> white
    if l > 0.8:
        FLAGS.add("fill")
        return (0x1b, 0x4b, 0x91, 1.0)            # light button fill -> navy fill
    return None

def convert(prop, value):
    p = prop.strip().lower()
    if p in ("color", "fill", "stroke", "caret-color", "text-decoration-color"): fn = map_text
    elif p.startswith("border") or p.startswith("outline") or p == "box-shadow": fn = map_line
    elif p.startswith("background") or p in ("mask-image", "--work-glass"): fn = map_bg if "mask" not in p else None
    else: return None
    if fn is None: return None
    changed = False
    def sub(m):
        nonlocal changed
        c = parse(m.group(0))
        if not c: return m.group(0)
        out = fn(*c)
        if not out: return m.group(0)
        changed = True
        return hexa(*out)
    new = COLOR.sub(sub, value)
    if p == "box-shadow" and changed: new = value  # shadows: keep the dark ones, drop light-on-dark inset glows below
    if p == "box-shadow":
        new = re.sub(r"inset [^,]*#(?:fff|ffffff)[0-9a-fA-F]{0,2}\b[^,]*", "inset 0 0 0 0 #0000", value)
        changed = new != value
    return new if changed else None

def blocks(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    i, stack, out, start = 0, [], [], 0
    while i < len(css):
        ch = css[i]
        if ch == "{":
            stack.append((css[start:i].strip(), i + 1)); start = i + 1
        elif ch == "}":
            sel, s = stack.pop()
            body = css[s:i]
            if "{" not in body: out.append((tuple(x[0] for x in stack if x[0].startswith("@")), sel, body))
            start = i + 1
        elif ch == ";" and not stack: start = i + 1
        i += 1
    return out

def split_sel(sel):
    parts, depth, cur = [], 0, ""
    for ch in sel:
        if ch in "([": depth += 1
        if ch in ")]": depth -= 1
        if ch == "," and depth == 0: parts.append(cur.strip()); cur = ""
        else: cur += ch
    parts.append(cur.strip()); return parts

def main():
    src = Path("src"); out = ["/* GENERATED by scripts/gen-light-theme.py (#619): do not edit by hand. */"]
    for name in ORDER:
        css = (src / f"{name}.css").read_text(encoding="utf-8")
        for media, sel, body in blocks(css):
            if sel.startswith("@") or any("keyframes" in m or "font-face" in m for m in media): continue
            decls = []; FLAGS.clear()
            for d in re.split(r";(?![^(]*\))", body):
                if ":" not in d: continue
                prop, val = d.split(":", 1)
                new = convert(prop, val.strip())
                if new is not None and not prop.strip().startswith("--"):
                    bang = " !important" if "!important" in new else ""
                    decls.append(f"{prop.strip()}: {new.replace('!important', '').strip()}{bang}")
            if "fill" in FLAGS and not any(d.startswith("color:") for d in decls): decls.append("color: #ffffff")
            if not decls: continue
            full = ",\n".join('html[data-theme="light"] ' + s for s in split_sel(sel) if not s.startswith(("html", ":root")))
            if not full: continue
            rule = f"{full} {{ {'; '.join(decls)}; }}"
            for m in reversed(media): rule = f"{m} {{\n{rule}\n}}"
            out.append(rule)
    Path("src/light-theme.generated.css").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(len(out) - 1, "rules")
main()
